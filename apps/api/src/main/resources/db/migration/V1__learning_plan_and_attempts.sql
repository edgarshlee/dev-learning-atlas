CREATE TABLE IF NOT EXISTS learning_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id VARCHAR(120) NOT NULL UNIQUE,
    status VARCHAR(32) NOT NULL,
    percentage INTEGER NOT NULL,
    note VARCHAR(2000),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE study_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path_id VARCHAR(160) NOT NULL,
    target_date DATE NOT NULL,
    learning_weekdays VARCHAR(100) NOT NULL,
    time_zone VARCHAR(80) NOT NULL,
    daily_minutes INTEGER NOT NULL,
    status VARCHAR(24) NOT NULL,
    resource_ids TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE daily_queue (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL,
    queue_date DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_daily_queue_plan FOREIGN KEY (plan_id) REFERENCES study_plan(id),
    CONSTRAINT uq_daily_queue_plan_date UNIQUE (plan_id, queue_date)
);

CREATE TABLE daily_queue_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    queue_id BIGINT NOT NULL,
    resource_id VARCHAR(120) NOT NULL,
    sort_order INTEGER NOT NULL,
    reason VARCHAR(32) NOT NULL,
    estimated_minutes INTEGER NOT NULL,
    postponed BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_daily_queue_entry_queue FOREIGN KEY (queue_id) REFERENCES daily_queue(id)
);

CREATE TABLE learning_attempt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL,
    resource_id VARCHAR(120) NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at TIMESTAMP WITH TIME ZONE,
    elapsed_minutes INTEGER,
    outcome VARCHAR(32),
    confidence INTEGER,
    reflection VARCHAR(1000),
    is_review BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_learning_attempt_plan FOREIGN KEY (plan_id) REFERENCES study_plan(id)
);

CREATE TABLE review_schedule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL,
    resource_id VARCHAR(120) NOT NULL,
    due_date DATE NOT NULL,
    stage INTEGER NOT NULL,
    CONSTRAINT fk_review_schedule_plan FOREIGN KEY (plan_id) REFERENCES study_plan(id),
    CONSTRAINT uq_review_schedule_plan_resource UNIQUE (plan_id, resource_id)
);

CREATE INDEX idx_daily_queue_entry_queue ON daily_queue_entry(queue_id);
CREATE INDEX idx_attempt_plan_resource ON learning_attempt(plan_id, resource_id);
CREATE INDEX idx_review_plan_due ON review_schedule(plan_id, due_date);
